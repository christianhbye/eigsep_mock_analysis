"""Where the paper's artifacts live, and the constants the two figures share.

Deliberately holds no analysis. `notebooks/horizon_shift.ipynb` and
`notebooks/signal_loss.ipynb` each derive the operating point and the 21 cm
selection from the raw inputs and then assert against the values here, so
these constants are a *contract* between the two figures rather than a
shortcut around either derivation. If a regenerated ensemble moves one of
them, both notebooks fail loudly instead of quietly disagreeing.

`EIGSEP_PAPER_NOTEBOOKS` overrides the output location, so a generator can be
pointed at a worktree instead of writing into the live paper directory.
"""

