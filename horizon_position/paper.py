ROOT = HERE.parent

# The paper repo's notebooks/ dir: a committed npz + a standalone notebook
# that regenerates the PDF, with the npz archived to Zenodo separately.
PAPER = Path(
    os.environ.get(
        "EIGSEP_PAPER_NOTEBOOKS",
        "/home/christian/Documents/research/papers/eigsep_instrument/notebooks",
    )
)
FG_NPZ = PAPER / "foreground_svd.npz"
